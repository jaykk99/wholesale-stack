/* Build the single-file dashboard-paste Worker.
 * Bundles src/worker.js (which pulls in service.js, core.js,
 * providers.js, store.js, page.js) with esbuild into ONE ES module.
 * The checkout page is generated in code (page.js), so there is no
 * ASSETS binding to inline. src/ is NOT modified.
 * Run: node dist-dashboard/build.mjs
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, copyFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tmp = mkdtempSync(join(tmpdir(), "ws-checkout-bundle-"));
const rawPath = join(tmp, "worker-raw.js");

execFileSync("npx", ["-y", "esbuild", "src/worker.js",
  "--bundle", "--format=esm", "--platform=neutral", "--target=es2022",
  `--outfile=${rawPath}`], { cwd: root, stdio: "inherit" });

const bundle = readFileSync(rawPath, "utf-8");
const header =
  "/* Wholesale Stack crypto checkout - single-file Worker for Cloudflare dashboard paste.\n" +
  " * Generated by dist-dashboard/build.mjs from cloudflare-checkout/src/ (do not edit by\n" +
  " * hand; edit src/ and rebuild). Binding required: D1 database bound as DB.\n" +
  " * Optional secret: PAYWATCH_CRON_SECRET (gates owner manual approval).\n" +
  " * Optional variable: PAYWATCH_PLANS_JSON (real plans replace the PLACEHOLDER tiers). */\n";

const out = join(root, "dist-dashboard", "worker.js");
writeFileSync(out, header + bundle);
copyFileSync(join(root, "migrations", "0001_init.sql"),
  join(root, "dist-dashboard", "migration.sql"));
console.log(`wrote ${out} (${Buffer.byteLength(header + bundle)} bytes)`);
console.log("copied dist-dashboard/migration.sql");
